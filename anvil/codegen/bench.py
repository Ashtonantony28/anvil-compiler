"""Cycle comparison of compiled schedules against the hand-written xf kernels (SG3b Accept).

    PYTHONPATH=sim python3 -m anvil.codegen.bench            # runs on Verilator, rewrites docs/codegen-bench.md

The MLP block of the mlp_block_0 fixture is lowered from graph IR (anvil.frontend.from_image), every kernel is
scheduled (matmuls with the `matmul_naive` / `matmul_tiled` templates, the other ops with the default schedule or
`row_per_block`) and compiled, and the whole chain runs as one Job per configuration. Hand-kernel cycles are the
published sim/bench/xf-mlp.json rows (sim/docs/xf-bench.md), which the SG0 tests reproduce exactly on Verilator.
Every compiled output is checked golden-equal in the same run.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
CONFIGS = ["", "COALESCE=1", "DCACHE_LINES=16", "COALESCE=1 DCACHE_LINES=16"]
TEMPLATE = {"naive": {"qlinear": "matmul_naive", "qmatmul": "matmul_naive"},
            "tiled": {"qlinear": "matmul_tiled", "qmatmul": "matmul_tiled"}}


def config_params(cfg: str, **kw):
    from ..runtime import GpuParams
    d = dict(kv.split("=") for kv in cfg.split())
    return GpuParams(**{k: int(v) for k, v in d.items()}, **kw)


def hand_rows():
    rows = json.loads((ROOT / "sim" / "bench" / "xf-mlp.json").read_text())["rows"]
    return {(r["params"], r["kind"], r["case"]): r for r in rows}


def compile_mlp(kind: str, params, block="mlp_block", **ckw):
    """(lowered Program, {name: CompiledKernel}, consts, fixture) for the MLP chain with `kind` matmuls."""
    from xf import fixture

    from ..frontend import from_image
    from ..lower.graph_to_tensor import lower
    from ..schedule import Schedule, Target, templates as T
    from . import compile_kernel
    d = fixture.load(fixture.FIXTURE_DIR / f"{block}_0.json")
    module, consts = from_image.BLOCKS[block](d["image"])
    prog = lower(module)
    tgt = Target.from_params(params, max_threads=4096)
    cks = {}
    for k in prog.kernels:
        tpl = TEMPLATE[kind].get(k.op)
        s = T.TEMPLATES[tpl](Schedule(k, tgt)) if tpl else T.default_schedule(k, tgt)
        cks[k.name] = compile_kernel(s.finalize(), params, **ckw)
    return prog, cks, consts, d


def run_mlp(kind: str, cfg: str = "", backend: str = "verilator", **ckw):
    """Run the compiled MLP chain; returns {kernel: (cycles, words, threads, counters)} and checks the goldens."""
    from ..runtime import run
    from . import program_job
    p = config_params(cfg)
    prog, cks, consts, d = compile_mlp(kind, p, **ckw)
    jp = program_job(prog, cks, {**consts, "x": d["inputs"]["x"]}, p)
    r = run(jp.job, backend)
    for name, want in d["golden"].items():
        got = jp.read(r.memory, name)
        if not np.array_equal(got, want):
            raise AssertionError(f"{kind} {cfg!r}: {name} differs from the golden")
    out, li = {}, 0
    for k in prog.kernels:
        ck = cks[k.name]
        lrs = r.launches[li:li + ck.launches]
        li += ck.launches
        cyc = None if lrs[0].cycles is None else sum(lr.cycles for lr in lrs)
        out[k.name] = (cyc, ck.program.stats["words"], sum(ck.threads(i) for i in range(ck.launches)),
                       {c: sum(lr.counters.get(c, 0) for lr in lrs) for c in lrs[0].counters})
    return out


CASES = ["h", "gate", "up", "act", "down", "out"]


def table(results) -> str:
    """results: {(cfg, kind): run_mlp output}."""
    hand = hand_rows()
    lines = ["| case | kind | config | hand cycles | compiled cycles | ratio | hand threads | compiled threads | "
             "compiled words |", "|---|---|---|---:|---:|---:|---:|---:|---:|"]
    for (cfg, kind), res in results.items():
        th = tc = 0
        for case in CASES:
            h = hand[(cfg, kind, case)]
            c, words, thr, _ = res[case]
            th, tc = th + h["cycles"], tc + c
            lines.append(f"| {case} | {kind} | {cfg or 'default'} | {h['cycles']} | {c} | {c / h['cycles']:.2f} | "
                         f"{h['threads']} | {thr} | {words} |")
        lines.append(f"| **total** | {kind} | {cfg or 'default'} | {th} | {tc} | {tc / th:.2f} | | | |")
    return "\n".join(lines)


def main(configs=CONFIGS, path=ROOT / "docs" / "codegen-bench.md"):
    results = {(cfg, kind): run_mlp(kind, cfg) for cfg in configs for kind in ("naive", "tiled")}
    text = f"""# Codegen bench: compiled schedules vs the hand-written xf kernels

Generated by `PYTHONPATH=sim python3 -m anvil.codegen.bench` (Verilator, cycle-exact with the iverilog RTL per
ADR-001); do not edit. The mlp_block_0 chain is lowered from graph IR, scheduled and compiled by
`anvil.codegen`; `kind` picks the matmul template (`matmul_naive` / `matmul_tiled`, mirroring
kernels/matmul_naive.asm / matmul_tiled.asm). The other
kernels use the default schedules (rmsnorm: one thread per row; elementwise ops: one thread per element), so the
`h`, `act` and `out` rows compare different algorithms from the hand kernels (rmsnorm.asm, for example, uses one
thread per element). Hand cycles: sim/bench/xf-mlp.json (sim/docs/xf-bench.md). Every compiled output is checked
golden-equal in the same run. `THREADS_PER_BLOCK=4`, `WARPS_PER_CORE=1`, `WORD_BITS=32`.

{table(results)}
"""
    Path(path).write_text(text)
    return results, text


if __name__ == "__main__":
    _, text = main()
    print(text)
