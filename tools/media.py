"""Render the README demo media into docs/media/.

    PYTHONPATH=sim:. python3 tools/media.py

  pipeline.png        one qlinear (y = requant(x @ w), 1x8x8) through every stage of the compiler, using the
                      real IR text each stage prints, ending in the isasim run checked against the golden model
  execute.{gif,mp4}   how the 'tiled' schedule maps that kernel onto tiny-gpu (2 blocks x 4 lanes, one output
                      column per lane); the values are the real inputs, and the final y is asserted equal to the
                      isasim run of the compiled program
  g3-cycles.png       chain cycles of hand-written kernels vs the compiler's presets and the autotuner, parsed
                      from docs/g3-report.md (generated by anvil.tune.g3_report on Verilator)
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "sim")]

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyBboxPatch  # noqa: E402

BG, PANEL, GRID, TXT, DIM = "#0d1117", "#161b22", "#30363d", "#e6edf3", "#8b949e"
BLUE, PURPLE, ORANGE, GREEN, RED, YELLOW = "#58a6ff", "#d2a8ff", "#ffa657", "#3fb950", "#f85149", "#e3b341"
MONO = "DejaVu Sans Mono"
OUT = ROOT / "docs" / "media"


def compile_mm():
    import anvil
    from anvil.runtime import GpuParams
    from anvil.tune.g3_report import mm_model
    (m, consts), d = mm_model()
    cm = anvil.compile((m, consts), params=GpuParams(), schedules="tiled")
    res = cm.run(d["inputs"]["x"], "isasim", quantized=True)
    y = np.asarray(res.ints["y"])
    assert np.array_equal(y, d["golden"]["y"]), "isasim result differs from the golden model"
    return m, consts, d, cm, y


def _trim(lines, keep):
    return [ln for ln in lines if any(re.search(p, ln) for p in keep)]


def pipeline(m, cm, y, golden):
    k = cm.program.kernels[0]
    ck = cm.kernels[k.name]
    graph = [re.sub(r'"anvil\.graph\.(\w+)"', r"graph.\1", ln.strip()) for ln in str(m).splitlines()
             if "anvil.graph." in ln and "func" not in ln]
    graph = [re.sub(r" : \(.*$", "", ln) for ln in graph]
    graph = [re.sub(r" <\{(M = \d+) : i64, (s = \d+) : i64.*?\}>", r" {\1, \2}", ln) for ln in graph]
    graph = [re.sub(r" <\{sym = (\S+)\}>", r" {\1}", ln) for ln in graph]
    tensor = []
    for ln in str(k.module).splitlines():
        s = ln.rstrip()
        if re.search(r'tensor\.(for|load|mul|add|requant|store)"', s):
            ind = (len(s) - len(s.lstrip())) // 2 - 2
            s = s.strip()
            mm = re.search(r'tensor\.for"\(\) <\{lb = (\d+).*ub = (\d+).*tag = "(\w+)"', s)
            if mm:
                s = f'for {mm.group(3)} in [{mm.group(1)}, {mm.group(2)}):'
            else:
                s = re.sub(r'"anvil\.tensor\.(\w+)"', r"\1", s)
                s = re.sub(r" <\{map = .*?\}>| : \(.*$", "", s)
                s = re.sub(r" <\{(M = \d+).*?(s = \d+).*?\}>", r" {\1, \2}", s)
            tensor.append("  " * max(0, ind) + s)
    sched_name, sched = cm.schedules[k.name]
    import json
    steps = [f"{op}({', '.join(json.dumps(a) for a in args)})" for op, args, _ in json.loads(sched)]
    asm = ck.program.asm_text.splitlines()
    hdr = [ln for ln in asm if ln.startswith("; args_base")][0]
    words = re.search(r"words=(\d+)", hdr).group(1)
    regs = re.search(r"regs_used=(\d+)", hdr).group(1)
    i0 = next(i for i, ln in enumerate(asm) if ln.startswith("Lloop"))
    body = [ln.rstrip() for ln in asm[i0 - 6:i0 + 20]]

    fig = plt.figure(figsize=(16, 9), dpi=100, facecolor=BG)
    fig.text(0.03, 0.94, "Anvil: one quantized linear layer through the compiler", fontsize=20, weight="bold", color=TXT)
    fig.text(0.03, 0.905, "y = requant(x @ w), x: 1x8 int8, w: 8x8 int8, target tiny-gpu-extended (2 cores x 4 threads).  "
             "Every panel is the real text that stage prints for this kernel (trimmed to the interesting lines).",
             fontsize=10.5, color=DIM)
    panels = [("1  graph IR", "torch.export / builder → anvil.graph", graph, BLUE),
              ("2  loop nest", "graph → anvil.tensor (scheduled loops)", tensor, PURPLE),
              (f"3  schedule  ('{'tiled'}' preset)", "transforms applied to the loop nest", steps
               + ["", "→ i·j fused, split by 4,", "  outer loop on blocks,", "  inner loop on thread lanes"], ORANGE),
              ("4  tiny-gpu assembly", f"register allocation (13 regs), {words} words, {regs} regs used", body, GREEN)]
    w, gap, x0 = 0.225, 0.015, 0.03
    for i, (title, sub, lines, col) in enumerate(panels):
        ax = fig.add_axes([x0 + i * (w + gap), 0.17, w, 0.70])
        ax.set_xlim(0, 1); ax.set_ylim(0, 1); ax.axis("off")
        ax.add_patch(FancyBboxPatch((0, 0), 1, 1, boxstyle="round,pad=0,rounding_size=0.02", fc=PANEL, ec=col, lw=1.5,
                                    transform=ax.transAxes))
        ax.text(0.04, 0.955, title, color=col, fontsize=13, weight="bold", va="top")
        ax.text(0.04, 0.905, sub, color=DIM, fontsize=8.8, va="top")
        fs = 9.6 if i != 1 else 8.4
        wrapped = []
        for ln in lines:
            while len(ln) > 40:
                cut = ln.rfind(" ", 0, 40)
                cut = cut if cut > 8 else 40
                wrapped.append(ln[:cut])
                ln = "      " + ln[cut:].lstrip()
            wrapped.append(ln)
        for j, ln in enumerate(wrapped[:26]):
            c = TXT
            if i == 3 and ln.startswith("Lloop"):
                c = YELLOW
            ax.text(0.04, 0.85 - j * 0.032, ln[:42], color=c, fontsize=fs, family=MONO, va="top")
        if i < 3:
            fig.text(x0 + (i + 1) * (w + gap) - gap / 2, 0.51, "›", color=DIM, fontsize=26, ha="center", va="center")
    fig.text(0.03, 0.11, "5  run on the ISA simulator", color=TXT, fontsize=13, weight="bold")
    fig.text(0.03, 0.07, f"y  = {np.asarray(y).ravel().tolist()}", color=TXT, fontsize=11.5, family=MONO)
    fig.text(0.03, 0.035, f"golden model = {np.asarray(golden).ravel().tolist()}", color=DIM, fontsize=11.5, family=MONO)
    fig.text(0.47, 0.052, "bit-exact ✓", color=GREEN, fontsize=15, weight="bold")
    fig.text(0.97, 0.035, "The same flow compiles the nanoGPT MLP block and attention head (docs/closeout.md).",
             color=DIM, fontsize=9.5, ha="right")
    fig.savefig(OUT / "pipeline.png", facecolor=BG)
    plt.close(fig)


def execute(consts, d, y_run, fps=4):
    x = np.asarray(d["inputs"]["x"]).ravel()
    w = np.asarray(consts["w"])
    K, N = w.shape
    Mq, sq = 17915, 22                                   # requant constants of mm_model's qlinear
    mm = g3_rows()["mm1x8x8"]
    tmp = Path(tempfile.mkdtemp())
    fig = plt.figure(figsize=(12.8, 7.2), dpi=100, facecolor=BG)
    acc = np.zeros(N, dtype=np.int64)
    frames = []
    for kk in range(K):
        acc = acc + x[kk] * w[kk]
        frames.append(("k", kk, acc.copy()))
    from anvil.semantics import requant
    yq = np.asarray(requant(acc, Mq, sq))
    assert np.array_equal(yq, np.asarray(y_run).ravel()), "illustration differs from the isasim run"
    seq = [("init", -1, np.zeros(N, np.int64))] * 3 + [f for f in frames for _ in range(2)] + [("rq", K, acc)] * 10
    for n, (ph, kk, a) in enumerate(seq):
        fig.clf()
        fig.text(0.035, 0.935, "How the compiled kernel runs on tiny-gpu", fontsize=18, weight="bold", color=TXT)
        fig.text(0.035, 0.905, "'tiled' schedule: output column j = 4·blockIdx + threadIdx, so 2 blocks (one per core) × "
                 "4 lanes each own one column and walk k together.\nValues are the real inputs of the compiled 1×8×8 qlinear; "
                 "the final y is checked against the ISA-simulator run of the compiled program.", fontsize=9.8, color=DIM, va="top")
        # x vector
        ax = fig.add_axes([0.06, 0.70, 0.40, 0.07]); ax.axis("off"); ax.set_xlim(-0.5, K - 0.5); ax.set_ylim(-0.5, 0.5)
        ax.text(-0.9, 0, "x", color=BLUE, fontsize=14, weight="bold", ha="right", va="center", family=MONO)
        for i in range(K):
            on = i == kk and ph == "k"
            ax.add_patch(plt.Rectangle((i - 0.45, -0.45), 0.9, 0.9, fc=BLUE if on else PANEL, ec=BLUE, lw=1))
            ax.text(i, 0, str(x[i]), ha="center", va="center", fontsize=10, family=MONO, color=BG if on else TXT)
        # w matrix
        ax = fig.add_axes([0.06, 0.20, 0.40, 0.46]); ax.axis("off"); ax.set_xlim(-0.5, N - 0.5); ax.set_ylim(K - 0.5, -1.4)
        ax.text(-0.9, (K - 1) / 2, "w", color=PURPLE, fontsize=14, weight="bold", ha="right", va="center", family=MONO)
        for r in range(K):
            for c in range(N):
                on = r == kk and ph == "k"
                ax.add_patch(plt.Rectangle((c - 0.45, r - 0.45), 0.9, 0.9, fc=PURPLE if on else PANEL,
                                           ec=PURPLE if on else GRID, lw=1))
                ax.text(c, r, str(w[r, c]), ha="center", va="center", fontsize=9, family=MONO, color=BG if on else TXT)
        for c in range(N):
            ax.text(c, -0.95, f"j={c}", ha="center", color=DIM, fontsize=8)
        ax.text(-0.9, kk if ph == "k" else -10, "k →", color=YELLOW, fontsize=9, ha="right", va="center")
        # lanes
        ax = fig.add_axes([0.52, 0.20, 0.45, 0.57]); ax.axis("off"); ax.set_xlim(0, 2); ax.set_ylim(4.2, -0.9)
        for b in range(2):
            ax.add_patch(FancyBboxPatch((b + 0.03, -0.55), 0.94, 4.6, boxstyle="round,pad=0,rounding_size=0.04",
                                        fc=PANEL, ec=ORANGE, lw=1.3))
            ax.text(b + 0.5, -0.72, f"core {b}: blockIdx {b}", ha="center", color=ORANGE, fontsize=11, weight="bold")
            for t in range(4):
                j = 4 * b + t
                ax.text(b + 0.08, t + 0.05, f"lane {t}  (j={j})", color=DIM, fontsize=9, va="center")
                if ph == "rq":
                    ax.text(b + 0.92, t - 0.15, f"acc {a[j]:>7d}", color=DIM, fontsize=9, family=MONO, ha="right",
                            va="center")
                    ax.text(b + 0.92, t + 0.22, f"y[{j}] = {yq[j]:>4d}", color=GREEN, fontsize=12, family=MONO,
                            ha="right", va="center", weight="bold")
                else:
                    ax.text(b + 0.92, t + 0.05, f"acc {a[j]:>7d}", color=TXT, fontsize=12, family=MONO, ha="right",
                            va="center")
        if ph == "k":
            step = f"k = {kk}:  every lane does  acc += x[{kk}] · w[{kk}, j]   (loop Lloop1: LDR, LDR, MUL, ADD)"
        elif ph == "rq":
            step = "requantize: y = clamp((acc·17915 + 2²¹) >> 22, −128, 127), STR to memory   ✓ equals the ISA-simulator run"
        else:
            step = "acc = 0 in every lane"
        fig.text(0.06, 0.10, step, color=YELLOW if ph != "rq" else GREEN, fontsize=11.5, family=MONO)
        fig.text(0.06, 0.05, f"Illustration of the schedule, not a cycle-level trace. On the Verilator RTL this schedule takes {mm[3]:,} "
                 f"cycles; the autotuned one {mm[4]:,} ({mm[4] / mm[0]:.2f}× the hand-written naive kernel).", color=DIM, fontsize=9)
        fig.savefig(tmp / f"f{n:04d}.png", facecolor=BG)
    plt.close(fig)
    ff = ["ffmpeg", "-loglevel", "error", "-y", "-framerate", str(fps), "-i", str(tmp / "f%04d.png")]
    subprocess.run(ff + ["-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "22", "-vf", "fps=12", str(OUT / "execute.mp4")],
                   check=True)
    subprocess.run(ff + ["-vf", "scale=960:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=48[p];"
                         "[b][p]paletteuse=dither=none", str(OUT / "execute.gif")], check=True)
    shutil.rmtree(tmp)


def g3_rows():
    """{workload: [hand naive, hand tiled, default, tiled, tuned]} cycles, default GPU config, from docs/g3-report.md."""
    rows = {}
    for ln in (ROOT / "docs" / "g3-report.md").read_text().splitlines():
        cells = [c.strip().strip("*") for c in ln.strip("|").split("|")]
        if len(cells) > 7 and cells[1] == "default" and cells[0] in ("mlp_block", "attention", "mm1x8x8"):
            rows[cells[0]] = [int(c) for c in cells[2:7]]
    return rows


def g3_cycles():
    rows = g3_rows()
    labels = ["hand naive", "hand tiled", "compiler default", "compiler tiled", "autotuned"]
    cols = [GRID, DIM, PURPLE, BLUE, GREEN]
    fig, axes = plt.subplots(1, 2, figsize=(12.8, 4.8), dpi=100, facecolor=BG)
    for ax, key, name in zip(axes, ("mlp_block", "attention"), ("nanoGPT MLP block", "nanoGPT attention head")):
        v = rows[key]
        ax.set_facecolor(BG)
        bars = ax.barh(range(5)[::-1], v, color=cols, height=0.62)
        for b, val in zip(bars, v):
            ax.text(val + max(v) * 0.01, b.get_y() + b.get_height() / 2, f"{val:,}" + (f"   {val / v[1]:.2f}× hand tiled"
                    if val == v[4] else ""), va="center", color=TXT, fontsize=10)
        ax.set_yticks(range(5)[::-1]); ax.set_yticklabels(labels, color=TXT, fontsize=10.5)
        ax.set_xlim(0, max(v) * 1.35); ax.tick_params(colors=DIM)
        ax.set_title(name, color=TXT, fontsize=13, loc="left", weight="bold")
        ax.set_xlabel("cycles (Verilator RTL, bit-exact)", color=DIM)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        for s in ("left", "bottom"):
            ax.spines[s].set_color(GRID)
    fig.suptitle("Compiled from PyTorch with no hand-written assembly, then autotuned", color=TXT, fontsize=15,
                 x=0.02, ha="left", y=0.97, weight="bold")
    fig.text(0.02, 0.875, "Source: docs/g3-report.md (seed 0, 200 measured candidates per kernel, default GPU config).",
             color=DIM, fontsize=9.5)
    fig.tight_layout(rect=(0, 0, 1, 0.86))
    fig.savefig(OUT / "g3-cycles.png", facecolor=BG)
    plt.close(fig)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    m, consts, d, cm, y = compile_mm()
    pipeline(m, cm, y, d["golden"]["y"])
    execute(consts, d, y)
    g3_cycles()


if __name__ == "__main__":
    main()
