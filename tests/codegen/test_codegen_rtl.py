"""SG3b Accept (rtl): compiled kernels on the Verilog simulators.

* A sample of ops x schedules x configurations (WARPS_PER_CORE 2, SIMT_STACK=1 with SYNC predication, mask
  predication with inactive lanes, a split launch) on the iverilog RTL: memory equal to isasim and to the tensor
  interpreter.
* The two matmul templates in the full MLP chain on Verilator: golden-equal, cycles reported next to the hand
  kernels' (docs/codegen-bench.md, regenerated by `PYTHONPATH=sim python3 -m anvil.codegen.bench`;
  this test checks the published default-configuration rows are current)."""
import re
from pathlib import Path

import numpy as np
import pytest

from anvil.codegen import bench, compile_kernel, kernel_job
from anvil.runtime import run
from codegen_util import case, bad_flags, params, schedule, target

pytestmark = pytest.mark.rtl

SAMPLE = [
    ("mlp_block", "gate", "matmul_tiled", (4, 1, 0)),
    ("mlp_block", "h", "row_per_block", (4, 2, 0)),
    ("attention", "p", "row_per_block", (4, 2, 1)),
    ("attention", "scores", "matmul_naive", (4, 4, 1)),
    ("lut", "y", "elementwise", (4, 2, 0)),           # 15 elements: an inactive lane, mask predication
    ("lut", "y", "elementwise", (4, 1, 1)),           # the same with SYNC predication
    ("attention", "kT", "none", (4, 2, 1)),
]


@pytest.mark.parametrize("blk,name,tpl,cfg", SAMPLE, ids=str)
def test_rtl_equals_isasim(blk, name, tpl, cfg):
    k, bufs, _ = case(blk, name)
    p = params(*cfg)
    fin = schedule(k, tpl, target(p)).finalize()
    want = fin.run(dict(bufs))
    ck = compile_kernel(fin, p)
    plan = kernel_job(ck, {s: v for s, v in bufs.items() if s in ck.buffers})
    model = run(plan.job)
    assert not bad_flags(model, p.SIMT_STACK)
    rtl = run(plan.job, "rtl")
    assert rtl.memory[:plan.end] == model.memory[:plan.end]
    assert not plan.stray_writes(rtl.memory)
    for s in ck.buffers:
        assert np.array_equal(plan.read(rtl.memory, s), np.asarray(want[s])), s


@pytest.mark.parametrize("wpc,simt", [(2, 1), (4, 0)])
def test_rtl_barriers_with_inactive_lanes_and_warps(wpc, simt):
    """Barriers inside the lane-activity region: SYNC-divergent at SIMT_STACK=1, masked at 0; idle warps RET."""
    from test_codegen_predication import exchange_kernel
    p = params(8, wpc, simt)
    k, bufs = exchange_kernel(p)
    want = k.run(dict(bufs))
    ck = compile_kernel(k, p)
    plan = kernel_job(ck, bufs)
    model, rtl = run(plan.job), run(plan.job, "rtl")
    assert not bad_flags(model, simt)
    assert rtl.memory[:plan.end] == model.memory[:plan.end]
    assert np.array_equal(plan.read(rtl.memory, "y"), want["y"])


def test_rtl_split_launch():
    from test_codegen_predication import big_matmul
    from anvil.codegen import program_job
    prog, vals, ref = big_matmul(M=8, K=4, N=36)
    p = params(4, 1, 0)
    ck = compile_kernel(schedule(prog.kernels[0], "matmul_naive", target(p)).finalize(), p)
    assert ck.launches == 2
    jp = program_job(prog, {ck.name: ck}, vals, p)
    rtl = run(jp.job, "rtl")
    assert np.array_equal(jp.read(rtl.memory, "c"), ref["c"])
    assert rtl.memory[:jp.end] == run(jp.job).memory[:jp.end]


def _published(kind):
    text = (Path(bench.ROOT) / "docs" / "codegen-bench.md").read_text()
    out = {}
    for m in re.finditer(rf"^\| (\w+) \| {kind} \| default \| (\d+) \| (\d+) \|", text, re.M):
        out[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    return out


@pytest.mark.parametrize("kind", ["naive", "tiled"])
def test_matmul_templates_on_verilator_vs_hand_kernels(kind):
    res = bench.run_mlp(kind, "")                    # raises unless every output is golden-equal
    hand = bench.hand_rows()
    pub = _published(kind)
    for case_ in bench.CASES:
        cyc = res[case_][0]
        assert cyc and cyc > 0
        assert pub[case_] == (hand[("", kind, case_)]["cycles"], cyc), f"docs/codegen-bench.md is stale ({case_})"
    print({c: (hand[("", kind, c)]["cycles"], res[c][0]) for c in ("gate", "up", "down")})
